/* ----------------------------------------------------------------------------
   mmurr.ai — one-off generator for js/data/maps.js (the two data-centre maps).

   The maps used to load d3 + topojson from a CDN plus a 108KB world topology on
   every visit, just to draw two fixed outlines. This script does the projection
   once, offline, and writes the outlines as plain SVG path strings plus the
   projection's scale/translate. The page then places site markers with a few
   lines of maths (js/worldmap.js), so sites can still be edited by hand in
   js/data/sites-*.js without re-running anything here.

   Re-run only if the outlines or the map sizes change:
     npm i --no-save d3-geo@3 topojson-client@3
     curl -o /tmp/50m.json  https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json
     curl -o /tmp/110m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json
     node tools/build-maps.mjs /tmp/50m.json /tmp/110m.json js/data/maps.js
   Natural Earth data via world-atlas: public domain.
---------------------------------------------------------------------------- */
import { readFileSync, writeFileSync } from 'node:fs';
import { geoMercator, geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const [,, f50, f110, out] = process.argv;
const load = f => { const t = JSON.parse(readFileSync(f, 'utf8')); return feature(t, t.objects.countries); };
const c50 = load(f50), c110 = load(f110);
const round = n => +n.toFixed(4);

// UK: 50m outline (the 110m one is too coarse at this size), Mercator.
const gb = c50.features.find(f => String(f.id) === '826');
const UK = { W: 460, H: 560 };
const pUK = geoMercator().fitExtent([[10, 10], [UK.W - 10, UK.H - 10]], gb);
const ukPath = geoPath(pUK).digits(1)(gb);

// World: 110m outlines, Natural Earth projection. Antarctica dropped (no sites,
// and it takes a fifth of the frame).
const world = { type: 'FeatureCollection', features: c110.features.filter(f => String(f.id) !== '010') };
const WD = { W: 920, H: 440 };
const pW = geoNaturalEarth1().fitExtent([[4, 4], [WD.W - 4, WD.H - 4]], world);
const wPath = geoPath(pW).digits(0);   // whole pixels are plenty at 920px wide
const countries = world.features.map(f => [+f.id || 0, f.properties.name, wPath(f)]).filter(r => r[2]);

// Self-check: the runtime formulas in js/worldmap.js must match d3 exactly.
const merc = ([lon, lat], k, tx, ty) => { const l = lon * Math.PI / 180, p = lat * Math.PI / 180;
  return [k * l + tx, ty - k * Math.log(Math.tan(Math.PI / 4 + p / 2))]; };
const ne1 = ([lon, lat], k, tx, ty) => { const l = lon * Math.PI / 180, p = lat * Math.PI / 180, p2 = p * p, p4 = p2 * p2;
  const x = l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4)));
  const y = p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)));
  return [k * x + tx, ty - k * y]; };
for (const pt of [[-0.12, 51.5], [-3.2, 55.95], [-1.47, 55.02]]) {
  const a = pUK(pt), b = merc(pt, pUK.scale(), ...pUK.translate());
  if (Math.hypot(a[0] - b[0], a[1] - b[1]) > 0.01) throw new Error('UK projection mismatch');
}
for (const pt of [[-0.12, 51.5], [-122.4, 37.8], [139.7, 35.7], [151.2, -33.9]]) {
  const a = pW(pt), b = ne1(pt, pW.scale(), ...pW.translate());
  if (Math.hypot(a[0] - b[0], a[1] - b[1]) > 0.01) throw new Error('world projection mismatch');
}

const data = {
  uk: { W: UK.W, H: UK.H, proj: { type: 'mercator', k: round(pUK.scale()), tx: round(pUK.translate()[0]), ty: round(pUK.translate()[1]) }, d: ukPath },
  world: { W: WD.W, H: WD.H, proj: { type: 'naturalEarth1', k: round(pW.scale()), tx: round(pW.translate()[0]), ty: round(pW.translate()[1]) }, countries },
};
writeFileSync(out, `/* GENERATED by tools/build-maps.mjs — do not edit by hand.
   Pre-projected map outlines (Natural Earth via world-atlas, public domain):
   UK at 1:50m (Mercator), world at 1:110m (Natural Earth 1, no Antarctica).
   [numeric country id, name, SVG path]. */
window.MMURR_MAPS = ${JSON.stringify(data)};
`);
console.log(`wrote ${out}: UK path ${ukPath.length} chars, ${countries.length} countries`);
