/* ----------------------------------------------------------------------------
   mmurr.ai — refresh js/data/api-prices.js from the LiteLLM community registry.

   Run:  node tools/refresh-prices.mjs        (also run weekly by the
         .github/workflows/refresh-prices.yml Action)

   Maps each model lineage on the prices page (models.axis keys in
   js/factors.js) to LiteLLM model IDs — first candidate found wins, so a
   renamed/removed upstream ID degrades gracefully to the next candidate, and a
   lineage with no match is simply omitted (the site falls back to its hand-set
   anchors). Output is a plain script-tag global so the site stays static and
   works on file:// with zero runtime network calls.
---------------------------------------------------------------------------- */
const SOURCE = 'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';

// axis key → LiteLLM ID candidates for the lineage's CURRENT model only.
// Each list must name the same model as the lineage's latest step in
// factors.js. Do NOT keep older models as fallbacks: if the current ID is
// missing, the lineage should keep its hand-set anchor, not take an older
// model's price (that once threatened to add a "Haiku 4.5" step after the
// chart had moved to Haiku 5.5). When a lineage moves on, update its step in
// factors.js and its entry here together.
const MAP = {
  'oa:auto':  ['gpt-6.1-sol'],
  'oa:think': [],                     // GPT-6 tiers don't map onto "Thinking" yet; anchors only
  'oa:mini':  ['gpt-6-luna'],
  'gm:flash': ['gemini/gemini-3.8-flash'],
  'gm:pro':   ['gemini/gemini-3.1-pro-preview', 'gemini-3.1-pro-preview'],
  'an:haiku': ['claude-haiku-5-5'],
  'an:sonnet':['claude-sonnet-5-5'],
  'an:opus':  ['claude-opus-5-5'],
  'an:fable': ['claude-fable-5-2'],
  'xa:grok':  ['xai/grok-4.7'],
  'mi:large': ['mistral/mistral-large-4', 'mistral/mistral-large-4-0'],
};

// New-model watch: the families the site tracks. Any ID in these families
// that wasn't in the registry at the last refresh is reported, so a new
// release prompts a human update instead of the site silently going stale.
// Dated snapshots and specialist variants are ignored to keep the list short.
const FAMILY = /^(gpt-\d|claude-(haiku|sonnet|opus|fable|mythos)-|gemini\/gemini-\d|xai\/grok-\d|mistral\/mistral-(large|medium)-)/;
const NOISE = /(\d{4}-\d{2}-\d{2}|-\d{8}|-\d{4}$|preview|latest|image|tts|live|transcribe|translate|codex|search|audio|realtime|cyber|vision|exp|beta|reasoning|multi-agent|customtools|chat|-gv\d|-law|-rosalind)/;

const reg = await (await fetch(SOURCE)).json();

// "since" = the first refresh that saw this exact price. js/factors.js uses it to
// date a price change, so a cut shows up when it happened instead of being
// backdated to the model's launch month. Carried forward from the previous file.
const { readFileSync, existsSync } = await import('fs');
const prevPath = new URL('../js/data/api-prices.js', import.meta.url);
let prev = {};
if (existsSync(prevPath)) {
  const w = {}; new Function('window', readFileSync(prevPath, 'utf8'))(w);
  prev = (w.MMURR_API_PRICES && w.MMURR_API_PRICES.models) || {};
}
const today = new Date().toISOString().slice(0, 10);

const models = {};
const misses = [];
for (const [axisKey, candidates] of Object.entries(MAP)) {
  const hit = candidates.find(id => {
    const m = reg[id];
    return m && m.input_cost_per_token > 0 && m.output_cost_per_token > 0;
  });
  if (!hit) { misses.push(axisKey); continue; }
  const m = reg[hit];
  const price = {
    id: hit,
    in:  +(m.input_cost_per_token  * 1e6).toFixed(4),   // USD / 1M tokens
    out: +(m.output_cost_per_token * 1e6).toFixed(4),
  };
  const p = prev[axisKey];
  price.since = p && p.id === price.id && p.in === price.in && p.out === price.out && p.since ? p.since : today;
  models[axisKey] = price;
}

const seen = Object.keys(reg).filter(id => FAMILY.test(id) && !NOISE.test(id)).sort();
let prevSeen = null;
if (existsSync(prevPath)) {
  const w = {}; new Function('window', readFileSync(prevPath, 'utf8'))(w);
  prevSeen = (w.MMURR_API_PRICES && w.MMURR_API_PRICES.seen) || null;
}
// First run with this feature (no previous list) reports nothing.
const newIds = prevSeen ? seen.filter(id => !prevSeen.includes(id)) : [];

const out = `/* GENERATED by tools/refresh-prices.mjs — do not edit by hand.
   Current API $/1M-token prices referenced from the LiteLLM community
   registry. History steps stay hand-set and dated in js/factors.js; when a
   price here differs from a lineage's latest step, the site adds a new step
   dated at "since" (the first refresh that saw it). Absent file / absent key →
   factors.js anchors are used unchanged. */
window.MMURR_API_PRICES = ${JSON.stringify({
    fetched: today,
    source: SOURCE,
    models,
    seen,
  }, null, 2)};
`;

const { writeFileSync, mkdirSync } = await import('fs');
const { dirname, join } = await import('path');
const { fileURLToPath } = await import('url');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
mkdirSync(join(root, 'js', 'data'), { recursive: true });
writeFileSync(join(root, 'js', 'data', 'api-prices.js'), out);

console.log(`wrote js/data/api-prices.js — ${Object.keys(models).length}/${Object.keys(MAP).length} lineages referenced`);
for (const [k, v] of Object.entries(models)) console.log(`  ${k.padEnd(10)} ${v.id.padEnd(34)} $${v.in}/$${v.out} per 1M`);
if (misses.length) console.log(`  (no match, anchors keep covering: ${misses.join(', ')})`);
if (newIds.length) {
  console.log(`NEW model IDs since the last refresh: ${newIds.join(', ')}`);
  // The workflow opens an issue from this list (GitHub emails the repo owner).
  if (process.env.GITHUB_OUTPUT) {
    const { appendFileSync } = await import('fs');
    appendFileSync(process.env.GITHUB_OUTPUT, `new_ids=${newIds.join(' ')}\n`);
  }
}
